def levenshtein_ratio_and_distance(s: str, t: str, ratio_calc: bool = False) -> float | str:
    """Calculate Levenshtein distance between two strings.

    Args:
        s: First string to compare.
        t: Second string to compare.
        ratio_calc: If True, return similarity ratio (0-1).
                   If False, return edit distance message.

    Returns:
        If ratio_calc is True, returns a float between 0 and 1 representing
        the similarity ratio. Otherwise, returns a string describing the
        edit distance.
    """
    rows = len(s) + 1
    cols = len(t) + 1
    distance = np.zeros((rows, cols), dtype=int)

    # Initialize first column and first row
    for i in range(rows):
        distance[i][0] = i
    for k in range(cols):
        distance[0][k] = k

    for col in range(1, cols):
        for row in range(1, rows):
            if s[row - 1] == t[col - 1]:
                cost = 0
            else:
                cost = 2 if ratio_calc else 1
            distance[row][col] = min(
                distance[row - 1][col] + 1,
                distance[row][col - 1] + 1,
                distance[row - 1][col - 1] + cost,
            )

    # Handle empty strings - use last indices of distance matrix
    final_row = rows - 1
    final_col = cols - 1

    if ratio_calc:
        # Avoid division by zero for two empty strings
        total_len = len(s) + len(t)
        if total_len == 0:
            return 1.0  # Two empty strings are identical
        ratio: float = (total_len - distance[final_row][final_col]) / total_len
        return ratio
    else:
        logger.debug(f"Distance matrix:\n{distance}")
        return f"The strings are {distance[final_row][final_col]} edits away"


